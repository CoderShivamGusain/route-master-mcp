"""Build the extension's page scripts from browser/scripts.py, so there's one source of truth.

Chrome extensions (Manifest V3) may not run code sent from a server, so the page logic has to
ship inside the extension. Instead of keeping a second copy, this module renders each script in
scripts.py with placeholder arguments and swaps each placeholder for a JavaScript argument
(`args.seats`, `args.site` ...). The result is written to
route-master-extension/page/actions.js, which defines `globalThis.__rm` in the content-script
world:

    __rm.capture()                                    → JSON string (same as CAPTURE_JS)
    __rm.select_seats({site, seats, seat_indexes})    → JSON string
    __rm.choose_points({site, boarding, dropping})
    __rm.decline_addons({})
    __rm.open_bus({site, operator, departure})        → marks the bus for a real click
    __rm.continue({site})                             → marks the next-step button

Regenerate after changing scripts.py:  python -m mcp_route_master.browser.extension_bundle
A test fails if the committed file is out of date.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from mcp_route_master.browser import scripts as ps

OUT = Path(__file__).resolve().parents[3] / "route-master-extension" / "page" / "actions.js"
_P = "__RMP_"


def _sub(js: str, pairs: dict[str, str]) -> str:
    for literal, expr in pairs.items():
        if literal not in js:
            raise ValueError(f"placeholder {literal} not found; scripts.py changed shape")
        js = js.replace(literal, expr)
    if _P in js or _P.lower() in js:
        raise ValueError("unreplaced placeholder left in a generated script")
    return js


def _q(name: str) -> str:
    return json.dumps(f"{_P}{name}__")


def build() -> str:
    site = {_q("site"): "args.site"}
    seats_rb = _sub(
        ps.select_seats_js("redBus", [f"{_P}seats__"]), {json.dumps([f"{_P}seats__"]): "(args.seats || [])"}
    )
    seats_mmt = _sub(
        ps.select_seats_js("MakeMyTrip", [], [f"{_P}idx__"]),  # type: ignore[list-item]
        {json.dumps([f"{_P}idx__"]): "(args.seat_indexes || [])"},
    )
    points = _sub(
        ps.choose_points_js(f"{_P}site__", f"{_P}b__", f"{_P}d__"),
        {**site, _q("b"): "String(args.boarding || '')", _q("d"): "String(args.dropping || '')"},
    )
    open_bus = _sub(
        ps.open_bus_js(f"{_P}site__", f"{_P}op__", f"{_P}dep__"),
        {
            **site,
            json.dumps(f"{_P}op__".lower()): "String(args.operator || '').trim().toLowerCase()",
            _q("dep"): "String(args.departure || '').trim()",
        },
    )
    parts = [
        "// GENERATED by mcp_route_master/browser/extension_bundle.py from browser/scripts.py. Do not edit.",
        "// Page logic for the route-master extension: the same scripts the open server gives AI apps.",
        "globalThis.__rm = {",
        f"  capture: (args) => {ps.CAPTURE_JS},",
        f"  select_seats: (args) => args.site === 'MakeMyTrip' ? {seats_mmt} : {seats_rb},",
        f"  choose_points: (args) => {points},",
        f"  decline_addons: (args) => {ps.DECLINE_ADDONS_JS},",
        f"  open_bus: (args) => {open_bus},",
        f"  continue: (args) => args.site === 'MakeMyTrip' ? {ps.continue_js('MakeMyTrip')} : {ps.continue_js('redBus')},",
        "};",
        "",
    ]
    return "\n".join(parts)


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
